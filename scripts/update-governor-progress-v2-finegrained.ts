async function main() {
  for (const g of govs) {
    const politician = await prisma.politician.findFirst({
      where: { level: "governor", region: g.region, name: g.name, office: g.office },
    });
    if (!politician) {
      console.warn(`governor not found: ${g.name} (${g.office}, ${g.region})`);
      continue;
    }
    for (const j of g.pledges) {
      const pledge = await prisma.pledge.findFirst({
        where: { politicianId: politician.id, source: "nec", order: j.order },
      });
      if (!pledge) {
        console.warn(`  no pledge order ${j.order} for ${g.name}`);
        continue;
      }
      await prisma.pledge.update({
        where: { id: pledge.id },
        data: {
          status: "in_progress",
          progressPercent: j.percent,
          statusNote: j.note,
          statusSource: j.source || null,
          statusCheckedAt: new Date(),
        },
      });
    }
    console.log(`${g.name} (${g.office}) updated`);
  }
}

main().finally(() => prisma.$disconnect());
